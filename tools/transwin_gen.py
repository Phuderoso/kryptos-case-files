"""Cycle 12: undo a transposition, then rerun the generator-agnostic small-digit window test (case file 10).
Key fact used: with a position-free digit test, 'transpose then substitute' and 'substitute then transpose'
give the same crib pairing (p_j with C[t(j)]), so only the direction of t matters; both t and t^-1 are tried.
Writes data/tw_alpha.bin (themed alphabets), data/tw_perm.bin (int16 x 97 per transposition, -1 = null slot),
data/tw_perm.txt (names). Usage: python3 tools/transwin_gen.py [control]"""
import sys, itertools, random
sys.path.insert(0, "tools")
from kryptos_text import K4, KA
import re
AZ = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"; N = 97
# same plain-sight vocabulary as tools/k4_layers.py (read as text to avoid its data dependencies)
WORDS = re.search(r'WORDS = """(.*?)"""', open("tools/k4_layers.py").read(), re.S).group(1).split()
def keyed(w):                         # identical to tools/gromark_alphabet.keyed
    return "".join(dict.fromkeys(w + AZ))
def aca_columnar(w):                  # identical to tools/gromark_alphabet.aca_columnar
    kw = "".join(dict.fromkeys(w)); rows = keyed(kw)
    cols = [rows[j::len(kw)] for j in range(len(kw))]
    return "".join(c for _, c in sorted(zip(kw, cols)))
# ---- themed alphabets (style profile: K1/K2 used one KRYPTOS-keyed alphabet on both sides) ----
A = {"AZ": AZ, "KA": KA, "ZA": AZ[::-1], "AK": KA[::-1]}
for w in WORDS:
    A["k:" + w] = keyed(w); A["r:" + w] = keyed(w)[::-1]; A["c:" + w] = aca_columnar(w)
for w1 in WORDS:
    for w2 in WORDS:
        if w1 != w2:
            ph = w1 + w2; A["k2:" + ph] = keyed(ph); A["r2:" + ph] = keyed(ph)[::-1]; A["c2:" + ph] = aca_columnar(ph)
uniq = {}
for n, a in A.items(): uniq.setdefault(a, n)
alph = [(n, a) for a, n in uniq.items()]
# ---- transpositions: perm[j] = index into the carved CT paired with plaintext position j ----
def columnar(L, w, order):           # write rows of w, read columns in 'order' (ragged last row)
    rows = -(-L // w); out = []
    for c in order:
        out += [r * w + c for r in range(rows) if r * w + c < L]
    return out                       # out[k] = source index of k-th output letter
def route(L, w, v):                  # 8 route variants on a ragged grid of width w
    rows = -(-L // w); out = []
    cols = range(w) if v & 1 == 0 else range(w - 1, -1, -1)
    for ci, c in enumerate(cols):
        rr = list(range(rows))
        if v & 2: rr = rr[::-1]
        if v & 4 and ci % 2: rr = rr[::-1]
        out += [r * w + c for r in rr if r * w + c < L]
    return out
def rot_cw(seq, w):                  # K3 step: rows of w, rotate 90 deg clockwise, read rows (full grid)
    h = len(seq) // w; return [seq[(h - 1 - r) * w + c] for c in range(w) for r in range(h)]
def k3double(L, w1, w2):
    s = list(range(L)); return rot_cw(rot_cw(s, w1), w2)
def kw_order(word, w):
    k = "".join(dict.fromkeys(word))[:w]
    if len(k) < w: return None
    return [i for _, i in sorted((ch, i) for i, ch in enumerate(k))]
T = {}
def add(name, out, L=N, drop=None):
    """out[k] = source index (0..L-1) of the k-th transposed letter.
    L > 97 without drop: ragged grid, cells >= 97 are empty and skipped (Sanborn-style irregular grid).
    drop = q: K2-style omitted letter. The true text has 98 letters, cribs at the official positions,
    and the letter at true CT position q was left off the copper (carved index shifts by one after q)."""
    if drop is None:
        out = [j for j in out if j < N]
        inv = [None] * N
        for k, j in enumerate(out): inv[j] = k
        T[f"{name}/enc"] = inv; T[f"{name}/dec"] = out
    else:
        inv = [None] * L
        for k, j in enumerate(out): inv[j] = k
        for tag, m in (("enc", inv), ("dec", out)):
            T[f"{name}/{tag}"] = [-1 if m[j] == drop else m[j] - (m[j] > drop) for j in range(N)]
add("identity", list(range(N)))
for w in range(2, 9):
    for order in itertools.permutations(range(w)): add(f"col{w}:{''.join(map(str,order))}", columnar(N, w, order))
for w in range(9, 21):
    for word in WORDS:
        o = kw_order(word, w)
        if o: add(f"colkw{w}:{word}", columnar(N, w, o))
for w in range(2, 49):
    for v in range(8): add(f"route{w}v{v}", route(N, w, v))
for L, extra in ((97, 0), (98, 1), (99, 2), (100, 3)):
    divs = [d for d in range(2, L) if L % d == 0]
    for w1 in divs:
        for w2 in divs:
            add(f"k3x{w1}x{w2}@L{L}ragged", k3double(L, w1, w2), L)
            if L == 98:   # K2 precedent: one letter omitted from the carving, at any position q
                for q in range(98): add(f"k3x{w1}x{w2}@L98omit{q}", k3double(98, w1, w2), 98, q)
CT = K4
if len(sys.argv) > 1 and sys.argv[1] == "control":
    # planted: K3-like English PT with cribs, Quagmire-III style PA=CA=keyed(SHADOW), Vigenère with digits of
    # the K2 coordinates (base 10, never generated by a recurrence), then keyword columnar BERLIN (width 6)
    pt = ("SLOWLYTHEREMAINSOFPASSAGEDEBRISEASTNORTHEASTWEREREMOVEDWITHTREMBLINGHANDSANDIMADEATINYBERLINCLOCK"
          "BREACHINTHEUPPERLEFTHANDCORNER")
    pt = list(pt[:97]); pt[21:34] = "EASTNORTHEAST"; pt[63:74] = "BERLINCLOCK"; pt = "".join(pt)
    al = keyed("SHADOW"); dig = [3,8,5,7,6,5,7,7,8,4,4]; s = 11
    mid = "".join(al[(al.index(p) + s + dig[i % len(dig)]) % 26] for i, p in enumerate(pt))
    out = columnar(N, 6, kw_order("BERLIN", 6)); CT = "".join(mid[j] for j in out)
    print("control CT", CT)
open("data/tw_ct.txt", "w").write(CT + "\n")
with open("data/tw_alpha.bin", "wb") as f:
    for n, a in alph: f.write(bytes(ord(c) - 65 for c in a))
open("data/tw_alpha.txt", "w").write("\n".join(n for n, _ in alph) + "\n")
import struct
with open("data/tw_perm.bin", "wb") as f:
    for n, p in T.items(): f.write(struct.pack("<97h", *p))
open("data/tw_perm.txt", "w").write("\n".join(T) + "\n")
nsingle = sum(1 for n, _ in alph if not n.startswith(("k2:", "r2:", "c2:")))
open("data/tw_nsingle.txt", "w").write(str(nsingle) + "\n")
print("alphabets", len(alph), "single-word", nsingle, "transpositions", len(T))
