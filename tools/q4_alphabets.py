AZ = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
def kw(w):
    s = ""
    for c in w + AZ:
        if c not in s: s += c
    return s
seen = []; names = []
for w in W:
    for tag, a in ((w, kw(w)), (w + "_rev", kw(w)[::-1])):
        if a not in seen and a != AZ: seen.append(a); names.append(tag)
A = np.array([[ord(c) - 65 for c in a] for a in [AZ] + seen], dtype=np.uint8)
A.tofile("q4_alpha.bin"); open("q4_alpha_names.txt", "w").write("\n".join(["AZ"] + names))
